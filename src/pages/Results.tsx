import React, { useEffect, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { CheckCircle, AlertCircle, ArrowLeft, Download, Share, Leaf, Droplets } from 'lucide-react';

interface DetectionResult {
  detections: Array<{
    class: string;
    confidence: number;
    bbox: number[];
  }>;
}

interface PrecautionsData {
  disease_name: string;
  immediate_actions: string[];
  short_term_management: string[];
  long_term_prevention: string[];
  organic_alternatives: string[];
  safety_precautions: string[];
  yield_impact: string[];
  fertilizer_recommendations?: any[];
  ai_generated?: boolean;
}

export const Results = () => {
  const [results, setResults] = useState<DetectionResult | null>(null);
  const [imagePreview, setImagePreview] = useState<string>('');
  const [precautions, setPrecautions] = useState<PrecautionsData | null>(null);
  const navigate = useNavigate();

  useEffect(() => {
    const storedResults = sessionStorage.getItem('detectionResults');
    const storedImage = sessionStorage.getItem('imagePreview');
    const storedPrecautions = sessionStorage.getItem('precautionsData');
    
    if (storedResults) {
      setResults(JSON.parse(storedResults));
    }
    if (storedImage) {
      setImagePreview(storedImage);
    }
    if (storedPrecautions) {
      setPrecautions(JSON.parse(storedPrecautions));
    }
  }, []);

  const getHealthStatus = () => {
    if (!results || results.detections.length === 0) {
      return { status: 'unknown', message: 'No detections found', color: 'gray' };
    }

    const hasDisease = results.detections.some(d => 
      !d.class.toLowerCase().includes('healthy')
    );

    if (hasDisease) {
      return { 
        status: 'disease', 
        message: 'Disease detected', 
        color: 'red' 
      };
    } else {
      return { 
        status: 'healthy', 
        message: 'Plant appears healthy', 
        color: 'green' 
      };
    }
  };

  const getConfidenceColor = (confidence: number) => {
    if (confidence >= 0.8) return 'text-green-600';
    if (confidence >= 0.6) return 'text-yellow-600';
    return 'text-red-600';
  };

  const handleNewScan = () => {
    sessionStorage.removeItem('detectionResults');
    sessionStorage.removeItem('imagePreview');
    sessionStorage.removeItem('precautionsData');
    navigate('/detect');
  };

  const handleDownloadReport = () => {
    if (!results) return;
    
    const report = `
AgriTech Disease Detection Report
=================================
Date: ${new Date().toLocaleString()}
Image: ${imagePreview ? 'Analyzed' : 'Not available'}

Results:
--------
${results.detections.map(d => 
  `Disease: ${d.class}\nConfidence: ${(d.confidence * 100).toFixed(1)}%\n`
).join('\n')}

Summary:
--------
${getHealthStatus().message}

This report was generated by AgriTech Plant Disease Detection System.
    `.trim();

    const blob = new Blob([report], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `agritech-report-${Date.now()}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  if (!results) {
    return (
      <div className="min-h-screen py-12">
        <div className="max-w-4xl mx-auto px-4 text-center">
          <h1 className="text-3xl font-bold text-gray-800 mb-4">
            No Results Found
          </h1>
          <p className="text-gray-600 mb-8">
            Please upload an image first to see detection results.
          </p>
          <button
            onClick={() => navigate('/detect')}
            className="px-6 py-2 bg-agri-green text-white rounded-lg hover:bg-agri-dark transition-colors"
          >
            Go to Detection
          </button>
        </div>
      </div>
    );
  }

  const healthStatus = getHealthStatus();

  return (
    <div className="min-h-screen py-12">
      <div className="max-w-6xl mx-auto px-4">
        <div className="mb-8">
          <button
            onClick={handleNewScan}
            className="flex items-center space-x-2 text-gray-600 hover:text-gray-800 transition-colors"
          >
            <ArrowLeft className="h-5 w-5" />
            <span>New Scan</span>
          </button>
        </div>

        <div className="text-center mb-8">
          <h1 className="text-4xl font-bold text-gray-800 mb-4">
            Detection Results
          </h1>
          <div className={`inline-flex items-center space-x-2 px-6 py-3 rounded-full ${
            healthStatus.color === 'green' ? 'bg-green-100 text-green-800' : 
            healthStatus.color === 'red' ? 'bg-red-100 text-red-800' : 
            'bg-gray-100 text-gray-800'
          }`}>
            {healthStatus.color === 'green' ? (
              <CheckCircle className="h-6 w-6" />
            ) : (
              <AlertCircle className="h-6 w-6" />
            )}
            <span className="font-semibold">{healthStatus.message}</span>
          </div>
        </div>

        <div className="grid lg:grid-cols-2 gap-8">
          {/* Image Preview */}
          <div className="bg-white rounded-lg shadow-lg p-6">
            <h2 className="text-xl font-semibold mb-4">Analyzed Image</h2>
            {imagePreview ? (
              <img
                src={imagePreview}
                alt="Analyzed plant"
                className="w-full rounded-lg shadow-md"
              />
            ) : (
              <div className="bg-gray-100 rounded-lg p-8 text-center text-gray-500">
                No image available
              </div>
            )}
          </div>

          {/* Detection Results */}
          <div className="bg-white rounded-lg shadow-lg p-6">
            <div className="flex justify-between items-center mb-4">
              <h2 className="text-xl font-semibold">Detection Details</h2>
              <div className="flex space-x-2">
                <button
                  onClick={handleDownloadReport}
                  className="p-2 text-gray-600 hover:text-gray-800 hover:bg-gray-100 rounded-lg transition-colors"
                  title="Download Report"
                >
                  <Download className="h-5 w-5" />
                </button>
                <button
                  className="p-2 text-gray-600 hover:text-gray-800 hover:bg-gray-100 rounded-lg transition-colors"
                  title="Share Results"
                >
                  <Share className="h-5 w-5" />
                </button>
              </div>
            </div>

            {results.detections.length > 0 ? (
              <div className="space-y-4">
                {results.detections.map((detection, index) => (
                  <div
                    key={index}
                    className={`p-4 rounded-lg border ${
                      detection.class.toLowerCase().includes('healthy')
                        ? 'bg-green-50 border-green-200'
                        : 'bg-red-50 border-red-200'
                    }`}
                  >
                    <div className="flex justify-between items-start mb-2">
                      <h3 className="font-semibold text-gray-800">
                        {detection.class}
                      </h3>
                      <span className={`text-sm font-medium ${getConfidenceColor(detection.confidence)}`}>
                        {(detection.confidence * 100).toFixed(1)}%
                      </span>
                    </div>
                    
                    <div className="text-sm text-gray-600">
                      <p>Confidence: {getConfidenceColor(detection.confidence).replace('text-', '')}</p>
                      <p>Location: [{detection.bbox.map(coord => coord.toFixed(0)).join(', ')}]</p>
                    </div>

                    {!detection.class.toLowerCase().includes('healthy') && (
                      <div className="mt-3 p-3 bg-yellow-50 border border-yellow-200 rounded text-sm text-yellow-800">
                        <strong>Recommendation:</strong> Consult with an agricultural expert for proper treatment.
                      </div>
                    )}
                  </div>
                ))}
              </div>
            ) : (
              <div className="text-center py-8 text-gray-500">
                <AlertCircle className="h-12 w-12 mx-auto mb-4 text-gray-400" />
                <p>No diseases detected in the image</p>
              </div>
            )}
          </div>
        </div>

        {/* AI-Powered Recommendations */}
        {precautions && (
          <div className="mt-8 bg-white rounded-lg shadow-lg p-6">
            <div className="flex items-center mb-4">
              {precautions.ai_generated && (
                <span className="bg-purple-100 text-purple-800 text-xs px-2 py-1 rounded-full mr-2">
                  AI Generated
                </span>
              )}
              <h2 className="text-2xl font-semibold text-gray-800 flex items-center">
                <Leaf className="w-6 h-6 mr-2 text-green-600" />
                Disease Management Recommendations
              </h2>
            </div>

            {precautions.immediate_actions && precautions.immediate_actions.length > 0 && (
              <div className="mb-6">
                <h3 className="text-lg font-semibold text-red-600 mb-3">Immediate Actions</h3>
                <ul className="list-disc pl-5 space-y-2 text-gray-700">
                  {precautions.immediate_actions.map((action, index) => (
                    <li key={index}>{action}</li>
                  ))}
                </ul>
              </div>
            )}

            {precautions.short_term_management && precautions.short_term_management.length > 0 && (
              <div className="mb-6">
                <h3 className="text-lg font-semibold text-yellow-600 mb-3">Short-Term Management</h3>
                <ul className="list-disc pl-5 space-y-2 text-gray-700">
                  {precautions.short_term_management.map((action, index) => (
                    <li key={index}>{action}</li>
                  ))}
                </ul>
              </div>
            )}

            {precautions.long_term_prevention && precautions.long_term_prevention.length > 0 && (
              <div className="mb-6">
                <h3 className="text-lg font-semibold text-green-600 mb-3">Long-Term Prevention</h3>
                <ul className="list-disc pl-5 space-y-2 text-gray-700">
                  {precautions.long_term_prevention.map((action, index) => (
                    <li key={index}>{action}</li>
                  ))}
                </ul>
              </div>
            )}

            {precautions.organic_alternatives && precautions.organic_alternatives.length > 0 && (
              <div className="mb-6">
                <h3 className="text-lg font-semibold text-blue-600 mb-3">Organic Alternatives</h3>
                <ul className="list-disc pl-5 space-y-2 text-gray-700">
                  {precautions.organic_alternatives.map((alternative, index) => (
                    <li key={index}>{alternative}</li>
                  ))}
                </ul>
              </div>
            )}

            {precautions.safety_precautions && precautions.safety_precautions.length > 0 && (
              <div className="mb-6">
                <h3 className="text-lg font-semibold text-orange-600 mb-3">Safety Precautions</h3>
                <ul className="list-disc pl-5 space-y-2 text-gray-700">
                  {precautions.safety_precautions.map((precaution, index) => (
                    <li key={index}>{precaution}</li>
                  ))}
                </ul>
              </div>
            )}

            {precautions.yield_impact && precautions.yield_impact.length > 0 && (
              <div className="mb-6">
                <h3 className="text-lg font-semibold text-purple-600 mb-3">Expected Yield Impact</h3>
                <ul className="list-disc pl-5 space-y-2 text-gray-700">
                  {precautions.yield_impact.map((impact, index) => (
                    <li key={index}>{impact}</li>
                  ))}
                </ul>
              </div>
            )}

            {precautions.fertilizer_recommendations && precautions.fertilizer_recommendations.length > 0 && (
              <div className="mt-6">
                <h3 className="text-lg font-semibold text-blue-600 mb-3 flex items-center">
                  <Droplets className="w-5 h-5 mr-2" />
                  Fertilizer Recommendations
                </h3>
                <div className="grid md:grid-cols-2 gap-4">
                  {precautions.fertilizer_recommendations.map((fertilizer, index) => (
                    <div key={index} className="border rounded-lg p-4 bg-gray-50">
                      <div className="flex justify-between items-start mb-2">
                        <h4 className="font-semibold text-gray-800">{fertilizer.name}</h4>
                        <span className="text-green-600 font-medium">{fertilizer.price_range}</span>
                      </div>
                      <p className="text-sm text-gray-600 mb-2">NPK Ratio: {fertilizer.npk_ratio}</p>
                      <p className="text-sm text-gray-600 mb-2">Type: {fertilizer.type}</p>
                      <p className="text-sm text-gray-600 mb-2">Application: {fertilizer.application_rate}</p>
                      <p className="text-sm text-gray-600 mb-3">Frequency: {fertilizer.frequency}</p>
                      <div className="text-sm text-gray-700">
                        <strong className="text-gray-800">Benefits:</strong>
                        <ul className="list-disc pl-4 mt-1">
                          {fertilizer.benefits.map((benefit: string, bIndex: number) => (
                            <li key={bIndex}>{benefit}</li>
                          ))}
                        </ul>
                      </div>
                    </div>
                  ))}
                </div>
              </div>
            )}
          </div>
        )}

        {/* Action Buttons */}
        <div className="mt-8 flex justify-center space-x-4">
          <button
            onClick={handleNewScan}
            className="px-6 py-3 bg-agri-green text-white rounded-lg hover:bg-agri-dark transition-colors"
          >
            Scan Another Image
          </button>
          <button
            onClick={() => navigate('/')}
            className="px-6 py-3 border border-gray-300 rounded-lg hover:bg-gray-50 transition-colors"
          >
            Back to Home
          </button>
        </div>

        {/* Additional Information */}
        <div className="mt-12 bg-blue-50 border border-blue-200 rounded-lg p-6">
          <h3 className="font-semibold text-blue-900 mb-3">Next Steps</h3>
          <div className="grid md:grid-cols-2 gap-4 text-sm text-blue-800">
            <div>
              <h4 className="font-medium mb-2">If disease detected:</h4>
              <ul className="space-y-1">
                <li>Isolate affected plants to prevent spread</li>
                <li>Consult local agricultural extension services</li>
                <li>Consider organic treatment options first</li>
                <li>Monitor plant health closely</li>
              </ul>
            </div>
            <div>
              <h4 className="font-medium mb-2">Prevention tips:</h4>
              <ul className="space-y-1">
                <li>Maintain proper plant spacing</li>
                <li>Ensure good air circulation</li>
                <li>Water at the base of plants</li>
                <li>Regularly inspect plants</li>
              </ul>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
